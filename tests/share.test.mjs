import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import {File} from 'node:buffer';
const source=readFileSync(new URL('../app.js',import.meta.url),'utf8');
const calls=[],dialogs=[];
const context=vm.createContext({URL,File,currentResult:{id:'usagi',name:'우사기',quote:'재밌겠는데?',type:'호기심이 앞서는 자유인'},navigator:{},cardCache:{blob:new Blob(['png'],{type:'image/png'})},openModal:html=>dialogs.push(html),modalTop:s=>s,icon:()=>'',toast:()=>{},esc:s=>s});
const base=source.match(/const SHARE_BASE='[^']+';/)[0];
vm.runInContext(base+'\n'+source.slice(source.indexOf('function shareURL'),source.indexOf('const loadImage='))+'\n'+source.slice(source.indexOf('async function shareCard'),source.indexOf('function restart')),context);
assert.equal(context.shareURL(),'https://mkr-games.github.io/Chiikawatest/?r=usagi&v=1');
assert.equal(context.shareURL(true),'https://mkr-games.github.io/Chiikawatest/?with=usagi');
context.navigator.share=async payload=>{calls.push(payload);};
await context.shareResult();
assert.equal(calls[0].url,context.shareURL());assert.equal(dialogs.length,0);
await context.shareResult(true);assert.equal(calls[1].url,context.shareURL(true));
context.navigator.share=async()=>{throw Object.assign(new Error('Canceled'),{name:'AbortError'});};
await context.shareResult();assert.equal(dialogs.length,0,'Cancellation must not trigger another dialog');
delete context.navigator.share;
await context.shareResult();assert.ok(dialogs.at(-1).includes('copy-result'));
await context.shareResult(true);assert.ok(dialogs.at(-1).includes('copy-invite'));
context.navigator.share=async payload=>{calls.push(payload);};
context.navigator.canShare=payload=>payload.files?.[0]?.type==='image/png';
await context.shareCard();assert.equal(calls.at(-1).files[0].name,'little-day-usagi.png');
console.log('Share checks passed: fixed URL, result/invite links, native sheet dispatch, cancel, fallback, PNG file payload. Actual device share targets require mobile QA.');
