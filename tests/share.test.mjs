import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import {File} from 'node:buffer';
import {BY_ID} from '../data.js';
import {SHARE_BASE,headline,caption,linkPayload,cardPayload} from '../personalization.js';
const source=readFileSync(new URL('../app.js',import.meta.url),'utf8');
const calls=[],copied=[],c=BY_ID.usagi;
const context=vm.createContext({URL,File,linkPayload,cardPayload,currentResult:c,navigator:{},cardCache:{blob:new Blob(['png'],{type:'image/png'}),name:'민구',character:c},copyLink:async s=>copied.push(s),toast:()=>{}});
vm.runInContext(source.slice(source.indexOf('async function shareResult'),source.indexOf('async function makeCard'))+'\n'+source.slice(source.indexOf('async function shareCard'),source.indexOf('async function copyCaption')),context);
context.navigator.share=async payload=>{calls.push(payload);};
await context.shareResult();assert.deepEqual(Object.keys(calls[0]),['url']);assert.equal(calls[0].url,SHARE_BASE);
await context.shareResult(true);assert.deepEqual(Object.keys(calls[1]),['url']);assert.equal(calls[1].url,SHARE_BASE+'?with=usagi');
context.navigator.share=async()=>{throw Object.assign(new Error('Canceled'),{name:'AbortError'});};
await context.shareResult();assert.equal(copied.length,0,'Cancel should not copy or open another action');
delete context.navigator.share;await context.shareResult();assert.equal(copied[0],SHARE_BASE);
context.navigator.share=async payload=>{calls.push(payload);};
context.navigator.canShare=payload=>payload.files?.[0]?.type==='image/png';
await context.shareCard();const payload=calls.at(-1);
assert.equal(payload.files[0].name,'little-day-usagi.png');
assert.equal(payload.title,"'민구'님은 우사기 성격이에요!");
assert.ok(payload.text.includes(c.intro)&&payload.text.includes('나도 해보기'));assert.equal(payload.url,SHARE_BASE);
assert.ok(caption('민구',c).includes(SHARE_BASE));assert.equal(headline('민구',c),payload.title);
context.navigator.canShare=payload=>!!payload.files&&!payload.url;
await context.shareCard();assert.deepEqual(Object.keys(calls.at(-1)),['files']);
console.log('PASS: link-only payload, named image + description + URL, cancel and copy/file-only fallback.');
